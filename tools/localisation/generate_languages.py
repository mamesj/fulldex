#!/usr/bin/env python3
"""localisation/languages.json -> frontend/ui_lang_codes.h (the enum, codes, names and properties of the languages).
--check: only verify the header is up to date."""
from pathlib import Path
import argparse, json, sys
sys.path.insert(0, str(Path(__file__).resolve().parent))
import languages
OUT = languages.ROOT / 'frontend/ui_lang_codes.h'
def render():
    langs = languages.load()
    ids = ', '.join(languages.ident(l['code']) for l in langs)
    def pred(name, key, doc):
        found = [languages.ident(l['code']) for l in langs if l[key]]
        body = ' || '.join('l == ' + i for i in found) if found else 'false'
        return [f'// {doc}', f'inline constexpr bool {name}(int l) {{ return {body}; }}']
    lines = ['#pragma once',
             '// Generated by tools/localisation/generate_languages.py from localisation/languages.json: do not edit here.',
             '// The menus\' languages. This is the only place a language\'s position is written down; everything else says',
             '// UiLang::Ja, never a bare number or a loose "ja". (The catalogue generators read the same file.)',
             'namespace UiLang',
             '{',
             '// The position of each language: UiLang::lang is one of these (an int, as it indexes tables).',
             f'enum Id : int {{ {ids}, CodeCount }};',
             'inline constexpr const char* Codes[CodeCount] = {' + ', '.join(json.dumps(l['code']) for l in langs) + '}; // (the locale codes, as saved)',
             'inline constexpr const char* Names[CodeCount] = {' + ', '.join(json.dumps(l['name'], ensure_ascii=False) for l in langs) + '}; // (as the menu shows them)',
             '// English is the language the text is written in: it needs no table, so it is never translated.',
             'inline constexpr bool IsEnglish(int l) { return l == En; }']
    lines += pred('IsTall', 'tall', 'Written in tall letters: lines are taller (Japanese, Korean).')
    lines += pred('HasCompanionText', 'companion', 'The Companion pages have their own text; the rest fall back to English.')
    lines += pred('HasOmegaNx', 'omega_nx', 'The omega-nx game has a menu in this language; the rest get English there.')
    lines += ['}', '']
    return '\n'.join(lines)
if __name__ == '__main__':
    a = argparse.ArgumentParser(); a.add_argument('--check', action='store_true'); o = a.parse_args()
    text = render()
    if o.check:
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != text: sys.exit('frontend/ui_lang_codes.h is out of date: run tools/localisation/generate_languages.py')
        print('language registry up to date')
    else:
        OUT.write_text(text, encoding='utf-8'); print('wrote', OUT)
