#!/usr/bin/env python3
"""The Companion pages' translations: localisation/companion_translations.json -> frontend/companion_translations.h.
The languages come from localisation/languages.json; one without a table here shows English.
--check: only verify the header is up to date and every table has the same keys and {n} places."""
from pathlib import Path
import argparse, json, re, sys
sys.path.insert(0, str(Path(__file__).resolve().parent))
import languages
ROOT = languages.ROOT
SRC = ROOT / 'localisation/companion_translations.json'
OUT = ROOT / 'frontend/companion_translations.h'
def render():
    tables = json.loads(SRC.read_text(encoding='utf-8'))['tables']
    known = languages.others()
    unknown = sorted(set(tables) - set(known))
    if unknown: sys.exit(f'companion_translations.json has tables for {unknown}, which languages.json does not list')
    codes = [c for c in known if c in tables]
    missing = [f for f in languages.flagged('companion') if f not in tables]
    if missing: sys.exit(f'languages.json says {missing} have Companion text (companion: true), but companion_translations.json has no table for them')
    for c in codes:
        if c not in languages.flagged('companion'):
            print(f'note: {c} has a Companion table but companion is false in languages.json, so its text is never shown', file=sys.stderr)
    keys = set(tables[codes[0]]) if codes else set()
    for c in codes:
        if set(tables[c]) != keys: sys.exit(f'{c}: not the same keys as {codes[0]}')
        for k, v in tables[c].items():
            if not v.strip(): sys.exit(f'{c}: empty translation for {k!r}')
            if sorted(re.findall(r'\{\d\}', k)) != sorted(re.findall(r'\{\d\}', v)): sys.exit(f'{c}: places differ in {k!r}')
    lines = ['#pragma once',
             '// Generated by tools/localisation/generate_companion_translations.py from localisation/companion_translations.json.',
             '// Authored UI translations adapted from PokeDaisy (GPL-3.0).',
             '// Based on PokeDaisy by Lidor Itzhari - https://github.com/lidor30/pokedaisy',
             '#include <string>', '#include <unordered_map>', '#include "ui_lang_codes.h"', 'namespace UiLang {',
             '// The text in `language` (a UiLang::Id), or as it is.',
             'inline std::string CompanionTranslation(int language, const std::string& text) {']
    for c in codes:
        lines += [f'    if (language == {languages.ident(c)}) {{', '        static const std::unordered_map<std::string, std::string> table = {']
        for k in sorted(tables[c]):
            lines.append('            {' + json.dumps(k, ensure_ascii=False) + ', ' + json.dumps(tables[c][k], ensure_ascii=False) + '},')
        lines += ['        };', '        const auto found = table.find(text);', '        return found == table.end() ? text : found->second;', '    }']
    lines += ['    return text;', '}', '}', '']
    return '\n'.join(lines)
if __name__ == '__main__':
    a = argparse.ArgumentParser(); a.add_argument('--check', action='store_true'); o = a.parse_args()
    text = render()
    if o.check:
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != text: sys.exit('frontend/companion_translations.h is out of date: run tools/localisation/generate_companion_translations.py')
        print('companion translations up to date')
    else:
        OUT.write_text(text, encoding='utf-8'); print('wrote', OUT)
