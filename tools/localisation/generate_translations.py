#!/usr/bin/env python3
"""Generate the portable interface tables from the reviewed UTF-8 catalogue."""
from pathlib import Path
import argparse,json
ROOT=Path(__file__).resolve().parents[2]
def render():
 d=json.loads((ROOT/'localisation/translations.json').read_text(encoding='utf-8'));tables=d['tables'];keys=set(tables['es'])
 if any(set(t)!=keys for t in tables.values()):raise ValueError('Language key coverage differs')
 lines=['// Generated by tools/localisation/generate_translations.py.','#pragma once','#include <string>','#include <unordered_map>','namespace UiTranslations {','// (A language is found by its code, not by a bare position. Same order as UiLang::Codes in ui_lang_codes.h; tests/test_language_order.py checks it.)','inline constexpr const char* Codes[] = {'+', '.join(json.dumps(c) for c in d['languages'])+'};','constexpr bool SameCode(const char* a, const char* b) { while (*a && *a == *b) { ++a; ++b; } return *a == *b; }','constexpr int IndexOf(const char* code) {','    for (int i = 0; i < int(sizeof(Codes) / sizeof(Codes[0])); ++i) if (SameCode(Codes[i], code)) return i;','    return -1;','}','inline const std::unordered_map<std::string,std::string>& Table(int language) {']
 for i,lang in enumerate(d['languages'][1:],1):
  lines+=['    static const std::unordered_map<std::string,std::string> '+lang+' = {']
  for key,value in sorted(tables[lang].items()):
   if not isinstance(value,str) or not value.strip():raise ValueError('Empty translation: '+lang+':'+key)
   lines+=['        {'+json.dumps(key,ensure_ascii=False)+', '+json.dumps(value,ensure_ascii=False)+'},']
  lines+=['    };']
 for lang in d['languages'][1:]:lines+=['    if (language == IndexOf("'+lang+'")) return '+lang+';']
 lines+=['    static const std::unordered_map<std::string,std::string> empty;','    return empty;','}','} // namespace UiTranslations','']
 return '\n'.join(lines)
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();out=ROOT/'frontend/ui_translations.h';text=render()
 if a.check:
  if not out.exists() or out.read_text(encoding='utf-8')!=text:p.exit(1,'Regenerate ui_translations.h\n')
 else:out.write_text(text,encoding='utf-8')
