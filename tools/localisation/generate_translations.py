#!/usr/bin/env python3
"""Generate the portable interface tables from the reviewed UTF-8 catalogue (localisation/translations.json).
The languages and their order come from localisation/languages.json. --check: only verify the header is up to date."""
from pathlib import Path
import argparse, json, sys
sys.path.insert(0, str(Path(__file__).resolve().parent))
import languages
ROOT = languages.ROOT
def render():
    d = json.loads((ROOT / 'localisation/translations.json').read_text(encoding='utf-8'))
    tables = d['tables']
    codes = languages.others()
    if set(tables) != set(codes): raise ValueError(f'translations.json has tables for {sorted(tables)}, languages.json asks for {codes}')
    keys = set(tables[codes[0]])
    if any(set(tables[c]) != keys for c in codes): raise ValueError('Language key coverage differs')
    lines = ['// Generated by tools/localisation/generate_translations.py.', '#pragma once', '#include <string>', '#include <unordered_map>',
             '#include "ui_lang_codes.h"', 'namespace UiTranslations {',
             '// (One table per language, built the first time that language is asked for; found by UiLang::Id, not by a bare position.)',
             'inline const std::unordered_map<std::string,std::string>& Table(int language) {']
    for code in codes:
        lines += [f'    if (language == UiLang::{languages.ident(code)}) {{', '        static const std::unordered_map<std::string,std::string> t = {']
        for key, value in sorted(tables[code].items()):
            if not isinstance(value, str) or not value.strip(): raise ValueError('Empty translation: ' + code + ':' + key)
            lines.append('            {' + json.dumps(key, ensure_ascii=False) + ', ' + json.dumps(value, ensure_ascii=False) + '},')
        lines += ['        };', '        return t;', '    }']
    lines += ['    static const std::unordered_map<std::string,std::string> empty;', '    return empty;', '}', '} // namespace UiTranslations', '']
    return '\n'.join(lines)
if __name__ == '__main__':
    p = argparse.ArgumentParser(); p.add_argument('--check', action='store_true'); a = p.parse_args()
    out = ROOT / 'frontend/ui_translations.h'; text = render()
    if a.check:
        if not out.exists() or out.read_text(encoding='utf-8') != text: p.exit(1, 'Regenerate ui_translations.h\n')
    else: out.write_text(text, encoding='utf-8')
